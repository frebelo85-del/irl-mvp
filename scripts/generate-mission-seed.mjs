#!/usr/bin/env node
/**
 * Generates supabase/migrations/00000002_seed_missions.sql from docs/missions.seed.json
 * Run from repo root: node scripts/generate-mission-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const seedPath = join(repoRoot, "docs", "missions.seed.json");
const outPath = join(repoRoot, "supabase", "migrations", "00000002_seed_missions.sql");

function sqlEscape(s) {
  return String(s).replaceAll("'", "''");
}

function main() {
  const raw = readFileSync(seedPath, "utf8");
  const { missions } = JSON.parse(raw);
  if (!Array.isArray(missions) || missions.length === 0) {
    throw new Error("missions.seed.json: expected non-empty missions[]");
  }

  const values = missions
    .map((m) => {
      const {
        id,
        category,
        teaser,
        title,
        body,
        locale,
      } = m;
      if (!id || !category || teaser == null || title == null || body == null) {
        throw new Error(`Mission missing fields: ${JSON.stringify(m)}`);
      }
      const loc = locale ?? "en";
      return (
        `  ('${sqlEscape(id)}'::uuid` +
        `, '${sqlEscape(category)}'::public.mission_category` +
        `, '${sqlEscape(teaser)}'` +
        `, '${sqlEscape(title)}'` +
        `, '${sqlEscape(body)}'` +
        `, '${sqlEscape(loc)}'` +
        ", true)"
      );
    })
    .join(",\n");

  const sql = `-- Generated by scripts/generate-mission-seed.mjs — source: docs/missions.seed.json\n` +
    `insert into public.missions (id, category, teaser, title, body, locale, is_active)\n` +
    `values\n${values}\n` +
    `on conflict (id) do update set\n` +
    `  category = excluded.category,\n` +
    `  teaser = excluded.teaser,\n` +
    `  title = excluded.title,\n` +
    `  body = excluded.body,\n` +
    `  locale = excluded.locale,\n` +
    `  is_active = excluded.is_active;\n`;

  writeFileSync(outPath, sql, "utf8");
  console.warn(`Wrote ${outPath} (${missions.length} missions)`);
}

main();
